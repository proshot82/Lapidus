local okV, vis = pcall(dofile, "build/l6j/vis.lua")
local R = require("core.rules")
local function tagOf(lvl, tag) for q, p in ipairs(lvl.pieces) do if p.tag == tag then return q end end end
-- Абляция роли «на муфту не встают»: запрещены состояния, где клетка тела лежит прямо на незакреплённой муфте.
local function noStool(lvl, st, ns)
  local q = tagOf(lvl, "cpl")
  local c = ns.pos[q]
  if c == 0 or ns.fixed[q] then return true end
  local up = lvl.nb[c][R.UP]
  for _, b in ipairs(ns.body) do if b == up then return false end end
  return true
end
-- Абляция роли «муфта не стоит под лазом»: муфта никогда не оказывается в клетке под лазом (5,7).
local function notUnderChimney(lvl, st, ns)
  local q = tagOf(lvl, "cpl")
  return ns.pos[q] ~= R.idx(lvl, 5, 7)
end

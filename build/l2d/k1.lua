-- Идея: та же шахта с двумя крючьями и унитазом над ней, тот же жилец; добавлена ОДНА муфта. Она лежит у Лапидуса на спине
-- в устье колодца рядом с крюком-отводом. Стоит освободить клетку под ней — муфта падает, ловится крюком и каменеет (M5):
-- это единственная ступенька к уступу и дальше к шахте. Но та же муфта наглухо закрывает карман, в котором Лапидус мог
-- развернуться. Уступ, колодец и шахта дальше — одна линия без развилок: каким концом Лапидус вышел на неё, тем и полезет.
-- Нижний крюк шахты берёт только голову (M1); ногами вперёд наверх не подняться, а развернуться уже негде.
-- «Ага» (подсказка №1): «Муфта каменеет там, куда упадёт, и закроет карман. Развернись, пока она у тебя на спине».
-- Ложный план: любой ход «от муфты» (в комнату) — муфта тут же падает на крюк, ступенька готова, всё выглядит правильно;
-- ошибка вскрывается только у нижнего крюка шахты, далеко от кармана.
-- Видимый проигрыш — общая линейка tools/vislib.lua (смыто; муфта, которая больше не сдвинется). Прикрученная муфта
-- стоит на своём единственном месте, поэтому «не тем концом» не видно ни новичку, ни знатоку.
local function tagOf(lvl, tag) for q, p in ipairs(lvl.pieces) do if p.tag == tag then return q end end end
-- абляция роли: муфта не каменеет (не прикручивается к крюку) — тогда, упав, она уходит в слив
local function noFix(lvl, st, ns)
  local q = tagOf(lvl, "cpl")
  return not ns.fixed[q]
end

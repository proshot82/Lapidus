-- build/l7v_d/mech.lua — честность правил: мини-примеры движка на поведение, которого нет на карточке кв. 7
-- (art/screens2.py pan_pressure: столб держит деталь над верхушкой; струя вбок толкает деталь; деталь, вошедшая
-- в первую клетку струи, прикручивается и глушит её). Проверяем, что реально делает ядро.
package.path = "./?.lua;" .. package.path
local R = require("core.rules")
local function L(grid, objects, len, pressure) return R.compile({ grid = grid, objects = objects, length = len or { 2, 5 }, pressure = pressure or 3 }) end
local function lap(cells, head) return { kind = "lapidus", cells = cells, head = head } end
local function body(lvl, st) local t = {} for _, c in ipairs(st.body) do t[#t + 1] = string.format("(%d,%d)", R.xy(lvl, c)) end return table.concat(t, " ") end
local function pos(lvl, st, q) if st.pos[q] == 0 then return "смыто" end local x, y = R.xy(lvl, st.pos[q]) return string.format("(%d,%d)", x, y) .. (st.fixed[q] and "F" or "") end

print("1. Неприкрученный Лапидус в столбе фонтана: поднимает ли столб его целиком, и что если над одной клеткой потолок")
do
  local g = { "#######", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#######" }
  local lvl = L(g, { { kind = "source", at = { 3, 6 }, ports = { up = "N" } }, lap({ { 4, 5 }, { 3, 5 } }, 2) })
  print("   без потолка: тело после устаканивания " .. body(lvl, R.newState(lvl)) .. "  (столб 3 клетки: (3,5),(3,4),(3,3))")
  local g2 = { "#######", "#.....#", "#.....#", "####..#", "#.....#", "#.....#", "#######" }
  local lvl2 = L(g2, { { kind = "source", at = { 5, 6 }, ports = { up = "N" } }, lap({ { 4, 5 }, { 5, 5 } }, 2) })
  print("   с потолком над одной клеткой: тело " .. body(lvl2, R.newState(lvl2)) .. "  (не поднят — «пробка»)")
end
print("2. Проходит ли струя сквозь неприкрученного Лапидуса (держит ли она деталь, брошенную сверху, при Лапидусе в столбе)")
do
  -- потолок над (4,3): ряд 3 = "####..#"; Лапидус (4,4)-(5,4), клетка (5,4) — в столбе (5,5),(5,4),(5,3)
  local g = { "#######", "#.....#", "####..#", "#.....#", "#.....#", "#.....#", "#######" }
  local lvl = L(g, { { kind = "source", at = { 5, 6 }, ports = { up = "N" } }, { kind = "fitting", at = { 5, 2 }, ports = { left = "N" } }, lap({ { 4, 4 }, { 5, 4 } }, 2) })
  local s = R.newState(lvl)
  print("   тело " .. body(lvl, s) .. "; деталь над столбом " .. pos(lvl, s, 2) .. " — столб проходит сквозь Лапидуса и держит деталь над верхушкой (5,2)")
end
print("3. «Пробка»: деталь без резьбы к стояку в ПЕРВОЙ клетке столба, над ней — клетка тела Лапидуса (потолок над плечами)")
do
  local g = { "#######", "#.....#", "####..#", "#.....#", "#.....#", "#.....#", "#######" }
  local lvl = L(g, { { kind = "source", at = { 5, 6 }, ports = { up = "N" } }, { kind = "fitting", at = { 5, 5 }, ports = { left = "N" } }, lap({ { 4, 4 }, { 5, 4 } }, 2) })
  local s = R.newState(lvl)
  print("   деталь " .. pos(lvl, s, 2) .. ", тело " .. body(lvl, s) .. " — деталь не поднимается: столб не толкает сквозь тело (карточка об этом молчит)")
end
print("4. Прикрученный Лапидус перекрывает струю (она не доходит до того, что за ним); неприкрученного она проходит и толкает")
do
  local g = { "##########", "#........#", "#........#", "##########" }
  local lvl = L(g, { { kind = "source", at = { 2, 3 }, ports = { right = "N" } }, { kind = "stub", at = { 4, 2 }, ports = { down = "N" } },
    { kind = "porcelain", at = { 6, 3 } }, lap({ { 5, 3 }, { 4, 3 } }, 2) })
  local s = R.newState(lvl)
  print("   голова прикручена к отводу над струёй, тело в струе; мыло за телом: " .. pos(lvl, s, 3) .. ", тело " .. body(lvl, s))
  local lvl2 = L(g, { { kind = "source", at = { 2, 3 }, ports = { right = "N" } }, { kind = "porcelain", at = { 6, 3 } }, lap({ { 5, 3 }, { 4, 3 } }, 2) })
  local s2 = R.newState(lvl2)
  print("   Лапидус не прикручен: мыло " .. pos(lvl2, s2, 2) .. ", тело " .. body(lvl2, s2) .. " (оба уехали до конца струи и дальше)")
end
print("5. Струя вбок толкает неприкрученного Лапидуса на клетку, затем он падает; ноги прикручиваются к ванне на лету")
do
  local g = { "#########", "#.......#", "#.......#", "#.......#", "###.....#", "#########" }
  local lvl = L(g, { { kind = "source", at = { 2, 3 }, ports = { right = "N" } }, { kind = "fixture", at = { 4, 5 }, ports = { up = "V" } },
    lap({ { 3, 3 }, { 3, 2 } }, 2) })
  local s = R.newState(lvl)
  local w = R.status(lvl, s)
  print("   ноги в первой клетке струи, тело вверх: тело " .. body(lvl, s) .. "; ноги прикручены к ванне: " .. tostring(w.heelQ ~= nil))
end
print("6. Порядок в шаге: струи раньше гравитации")
do
  local g = { "########", "#......#", "#......#", "#......#", "#......#", "########" }
  local lvl = L(g, { { kind = "source", at = { 2, 4 }, ports = { right = "N" } }, { kind = "porcelain", at = { 3, 2 } }, lap({ { 6, 2 }, { 6, 3 } }, 2) }, { 2, 5 }, 1)
  local s = R.newState(lvl)
  print("   мыло падает по столбцу 3 через клетку струи длиной 1 (3,4): итог " .. pos(lvl, s, 2) .. " — (4,5) значит «толкнуло, потом упало»; (3,5) значило бы «упало мимо»")
end
print("7. Лапидус стоит на детали, которую держит столб (опора через висящую деталь)")
do
  local g = { "#######", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#######" }
  local lvl = L(g, { { kind = "source", at = { 3, 6 }, ports = { up = "N" } }, { kind = "fitting", at = { 3, 2 }, ports = { left = "N" } }, lap({ { 3, 1 }, { 4, 1 } }, 2) })
  -- Лапидуса на стене нельзя; ставим его рядом и над деталью: (4,2) не опора, поэтому проверим через клетку над деталью (3,1) — стена; вместо этого:
  local g2 = { "#######", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#######" }
  local lvl2 = L(g2, { { kind = "source", at = { 3, 7 }, ports = { up = "N" } }, { kind = "fitting", at = { 3, 3 }, ports = { left = "N" } }, lap({ { 3, 2 }, { 4, 2 } }, 2) })
  local s = R.newState(lvl2)
  print("   деталь над верхушкой " .. pos(lvl2, s, 2) .. "; Лапидус на ней " .. body(lvl2, s) .. " (не упал — висящая деталь служит опорой)")
end
print("8. Столб останавливает Лапидуса под висящей деталью (деталь не сдвигается его подъёмом)")
do
  local g = { "#######", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#######" }
  local lvl = L(g, { { kind = "source", at = { 3, 7 }, ports = { up = "N" } }, { kind = "fitting", at = { 3, 3 }, ports = { left = "N" } }, lap({ { 2, 6 }, { 3, 6 } }, 2) })
  local s = R.newState(lvl)
  print("   тело " .. body(lvl, s) .. "; деталь " .. pos(lvl, s, 2) .. " — Лапидус поднят только до клетки под деталью")
end

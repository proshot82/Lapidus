-- Две роли одной детали: муфта — сначала ТАБУРЕТКА под лазом (иначе до полки слева не дотянуться), потом ЗВЕНО-КРЮК в стояке.
-- Ловушка-очевидность (скрытая): муфта лежит в одном толчке от стояка — вкрутить её сразу естественно, но тогда лаз
-- недоступен; на полку ещё можно подняться справа, только оттуда ниппель толкается в лаз, а не в шахту, и ложится на пол,
-- откуда его уже не поднять. Проигрыш становится видимым лишь когда ниппель падает (≥ 10 ходов после ошибки).
-- Побочные скрытые ошибки: ниппель сброшен в лаз при живой табуретке (откат длинный: везти по телу и поднимать снизу);
-- ниппель на полу у табуретки свинчивается с муфтой (пара никуда не вкрутится); ниппель на полу у стояка запирает стояк.

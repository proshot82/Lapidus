SRC = lambda x, y: {'kind': 'source', 'at': (x, y), 'ports': {'up': 'N'}}
CPL = lambda x, y: {'kind': 'fitting', 'what': 'coupling', 'at': (x, y), 'ports': {'up': 'V', 'down': 'V'}}
NIP = lambda x, y: {'kind': 'fitting', 'what': 'nipple', 'at': (x, y), 'ports': {'up': 'N', 'down': 'N'}}
def PIPE(x, y, out):
    return {'kind': 'pipe', 'at': (x, y), 'ports': {'down': 'V', out: 'N'}}
def WASH(x, y, side):
    return {'kind': 'fixture', 'what': 'washer', 'at': (x, y), 'ports': {side: 'V'}}
def LAP(cells, head):
    return {'kind': 'lapidus', 'cells': cells, 'head': head}


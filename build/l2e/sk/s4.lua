-- скелет s3: вертикальный проход слева (унитаз (3,2) порт вниз, стояк (3,7) порт вверх, шахта x=3 ряды 3..6),
-- коридор (4..5,6) в колодец 6..8 × 2..9; площадка старта 9..10 × 2..3 над правой стеной; пол на дне (нижний ярус).
-- Слоты: левая стена x=5 (ряды 3,4,5,7,8,9 — a..f, порт вправо), правая x=9 (ряды 4..9 — g..l, порт влево).
local R = {
"###########",
"##F##...12#",
"##.#a.....#",
"##.#b...g##",
"##.#c...h##",
"##......i##",
"##S#d...j##",
"####e...k##",
"####f...l##",
"###########",
}
local function withStart(r2, r3)
  local t = {}
  for i, r in ipairs(R) do t[i] = r end
  t[2] = r2; t[3] = r3
  return t
end
return {
  rows = R,
  slots = { a = "right", b = "right", c = "right", d = "right", e = "right", f = "right",
            g = "left", h = "left", i = "left", j = "left", k = "left", l = "left" },
  starts = {
    withStart("##F##...12#", "##.#a.....#"),
    withStart("##F##...21#", "##.#a.....#"),
    withStart("##F##....1#", "##.#a....2#"),
    withStart("##F##....2#", "##.#a....1#"),
    withStart("##F##...12#", "##.#a....3#"),
    withStart("##F##...32#", "##.#a....1#"),
    withStart("##F##....1#", "##.#a...32#"),
    withStart("##F##....3#", "##.#a...12#"),
  },
  opts = { src = "up:V", fx = "down:N", len = { 2, 4 } },
  optsSrc = '{ src = "up:V", fx = "down:N", len = { 2, 4 } }',
}
